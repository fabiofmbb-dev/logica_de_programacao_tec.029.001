# entrada de dados
n1 = int(input("informe o numero: "))
n2 = int(input("informe o segundo numero: "))
soma = n1 + n2
subtracao = n1 - n2
multiplicacao = n1 * n2
divisao = n1 / n2
resto = n1 % n2

# saida de dados
print(f"Soma: {soma} ")
print(f"Subtração: {subtracao} ")
print(f"Multiplicação: {multiplicacao}")
print(f"Divisão: {divisao}")
print(f"Resto da divisão: {resto}")
